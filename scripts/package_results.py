"""Create a local visual review report and runnable source archives without executing model code."""
import argparse
import html
import json
import statistics
import zipfile
from collections import Counter
from pathlib import Path

from frontendslm.io import sha256, write_json

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    return json.loads(path.read_text()) if path.exists() else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("run_id")
    args = parser.parse_args()
    run_dir = ROOT / "artifacts" / args.run_id
    if run_dir.parent != ROOT / "artifacts":
        raise ValueError("Expected a direct run directory")
    summary = load(run_dir / "summary.json")
    run = load(run_dir / "run.json")
    cases = {c["id"]: c for c in map(json.loads, (ROOT / "benchmarks/pilot_v1.jsonl").read_text().splitlines())}
    exports = run_dir / "exports"
    exports.mkdir(exist_ok=True)
    rows = {f"{r['baseline']}/{r['case_id']}": r for r in summary["rows"]}
    diagnostics = {"run_id": args.run_id, "baselines": {}, "human_review": "pending"}
    review_queue = []
    e = html.escape
    sections = []
    for case_id in run["case_ids"]:
        case = cases[case_id]
        cards = []
        for baseline in run["baselines"]:
            relative = f"{baseline}/{case_id}"
            path = run_dir / relative
            row = rows[relative]
            generation = load(path / "generation.json")
            evidence = load(path / "render/evidence.json") or {}
            critique = load(path / "critique.json") or {}
            archive = exports / f"{baseline}-{case_id}.zip"
            if generation and generation.get("manifest"):
                with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
                    for template in (ROOT / "sandbox").rglob("*"):
                        name = template.relative_to(ROOT / "sandbox")
                        if (template.is_file() and not set(name.parts) & {"node_modules", "dist"}
                                and str(name) != "evaluate.mjs" and str(name) not in generation["manifest"]["files"]):
                            z.write(template, str(name))
                    for name, content in generation["manifest"]["files"].items():
                        z.writestr(name, content)
                    z.writestr("README.txt", "Research candidate generated by an untouched small language model.\nRun npm ci, npm run build, npm run preview in an isolated environment.\nReview the accompanying evidence before use. External integrations are not provided.\n")
                    z.writestr("specification.json", json.dumps(case["spec"], indent=2))
                    z.writestr("acceptance-tests.json", json.dumps(case["tests"], indent=2))
                    z.writestr("validation.json", json.dumps(row, indent=2))
            preview = "<p class='missing'>No verified render available.</p>"
            if evidence.get("screenshots", {}).get("desktop"):
                preview = f"<a href='{relative}/render/desktop.png'><img class='desktop' loading='lazy' src='{relative}/render/desktop.png' alt='{e(baseline)} desktop screenshot'></a>"
                if evidence.get("screenshots", {}).get("mobile"):
                    preview += f"<a href='{relative}/render/mobile.png'><img class='mobile' loading='lazy' src='{relative}/render/mobile.png' alt='{e(baseline)} mobile screenshot'></a>"
            measures = [("Build", row["build_pass"]), ("Interactions", row["interaction_pass"]), ("No overflow", row["no_overflow"]),
                        ("Accessibility gate", row["no_serious_a11y"]), ("Critic schema", row["critic_schema_valid"]), ("Critic measurements", row.get("critic_measured_valid", False))]
            badges = " ".join(f"<span class='{'pass' if value else 'fail'}'>{name}: {'pass' if value else 'fail'}</span>" for name, value in measures)
            links = f"<a href='{relative}/generation.json'>Raw generation</a>"
            if evidence:
                links += f" · <a href='{relative}/render/evidence.json'>Browser evidence</a>"
            if archive.exists():
                links += f" · <a href='exports/{archive.name}'>Source ZIP</a>"
            details = ""
            if critique:
                details += f"<p>Effective verdict: {e(critique.get('effective_verdict', 'unavailable'))}</p><details><summary>Critic response</summary><pre>{e(critique.get('raw', ''))}</pre><p>{e(critique.get('error') or '')}</p></details>"
                review_queue.append({"candidate": relative, "specification": case["spec"],
                    "critique": critique.get("critique"), "raw_critique": critique.get("raw"),
                    "schema_valid": critique.get("schema_valid"), "reviewer": None, "issue_labels": [],
                    "missed_issues": [], "abstention_correct": None, "overall_visual_rating": None})
            if row.get("generation_error") or row.get("build_error") or row.get("harness_error"):
                error = row.get("generation_error") or row.get("build_error") or row.get("harness_error")
                details += f"<details><summary>Failure detail</summary><pre>{e(error)}</pre></details>"
            cards.append(f"<article><h3>{baseline} · {'Basic instruction' if baseline == 'A0' else 'Detailed design guidance'}</h3><div class='badges'>{badges}</div><div class='previews'>{preview}</div><p class='links'>{links}</p>{details}</article>")
        sections.append(f"<section><h2>{e(case_id.replace('_', ' ').title())}</h2><p class='brief'>{e(case['spec']['user_goal'])}</p><p class='style'>Style: {e(case['spec']['style']['descriptors'])}</p><div class='pair'>{''.join(cards)}</div></section>")
    for baseline in run["baselines"]:
        generations = [load(run_dir / baseline / c / "generation.json") for c in run["case_ids"]]
        critiques = [load(run_dir / baseline / c / "critique.json") for c in run["case_ids"]]
        events = Counter()
        for case_id in run["case_ids"]:
            evidence = load(run_dir / baseline / case_id / "render/evidence.json") or {}
            for view in evidence.get("views", {}).values():
                events.update(v["id"] for v in view.get("accessibility", []))
        valid_generations = [g for g in generations if g]
        valid_critiques = [c for c in critiques if c]
        diagnostics["baselines"][baseline] = {
            "critic_schema_valid_given_attempts": {"passed": sum(c["schema_valid"] for c in valid_critiques), "total": len(valid_critiques)},
            "generation_truncated_count": sum(g["truncated"] for g in valid_generations),
            "source_manifest_failure_count": sum(g["manifest"] is None for g in valid_generations),
            "source_manifest_failures": [{"case_id": g["case_id"], "truncated": g["truncated"], "error": g["error"]}
                                         for g in valid_generations if g["manifest"] is None],
            "architect_inference_seconds": sum(g["seconds"] for g in valid_generations),
            "architect_median_tokens_per_second": statistics.median(g["tokens_per_second"] for g in valid_generations) if valid_generations else None,
            "architect_peak_gpu_gib": max((g["peak_gpu_gib"] for g in valid_generations), default=None),
            "architect_output_tokens": sum(g["output_tokens"] for g in valid_generations),
            "critic_inference_seconds": sum(c["seconds"] for c in valid_critiques),
            "critic_output_tokens": sum(c["output_tokens"] for c in valid_critiques),
            "critic_peak_gpu_gib": max((c["peak_gpu_gib"] for c in valid_critiques), default=None),
            "accessibility_rule_view_occurrences": dict(events),
            "critic_measured_valid_given_attempts": {"passed": sum(bool((c.get("measurement_validation") or {}).get("valid")) for c in valid_critiques), "total": len(valid_critiques)},
            "critic_validation_failures": [{"case_id": c["case_id"], "error": c["error"]} for c in valid_critiques if not c["schema_valid"]],
        }
    table = "<table><thead><tr><th>Measured outcome</th>" + "".join(f"<th>{b}</th>" for b in run["baselines"]) + "</tr></thead><tbody>"
    for metric in ["build_pass", "interaction_pass", "no_overflow", "no_serious_a11y", "release_eligible", "critic_schema_valid"]:
        table += f"<tr><td>{metric.replace('_', ' ').title()}</td>" + "".join(f"<td>{summary['summary'][b][metric]['passed']} / {summary['summary'][b][metric]['total']}</td>" for b in run["baselines"]) + "</tr>"
    table += "</tbody></table>"
    document = f"""<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>FrontEndSLM baseline review</title>
<style>body{{margin:0;background:#f4f4f0;color:#172323;font:16px/1.6 system-ui,sans-serif}}main{{max-width:1500px;margin:auto;padding:48px 28px}}h1{{font-size:44px;letter-spacing:-.04em;line-height:1.1}}h2{{font-size:28px;margin:0}}h3{{font-size:17px}}.intro{{max-width:850px;color:#455454}}a{{color:#14604d}}section{{margin-top:48px;padding-top:32px;border-top:1px solid #cfd6d1}}.brief{{max-width:1000px}}.style{{color:#63726a}}.pair{{display:grid;grid-template-columns:1fr 1fr;gap:20px}}article{{background:white;border:1px solid #dce2dc;border-radius:12px;padding:20px;min-width:0}}.previews{{display:flex;align-items:start;gap:10px;margin-top:20px;overflow:hidden}}.previews a:first-child{{width:77%}}.previews a:nth-child(2){{width:21%}}img{{width:100%;height:auto;border:1px solid #dce2dc;border-radius:4px}}.badges{{display:flex;flex-wrap:wrap;gap:6px;font-size:12px}}.badges span{{padding:3px 7px;border-radius:4px}}.pass{{background:#e0f4e9;color:#175238}}.fail{{background:#fce6df;color:#8b3320}}pre{{font-size:12px;white-space:pre-wrap;word-break:break-word;max-height:450px;overflow:auto}}details{{border-top:1px solid #ddd;padding:12px 0}}summary{{cursor:pointer}}.links{{font-size:13px}}table{{border-collapse:collapse;background:white;width:min(700px,100%)}}th,td{{padding:10px 18px;text-align:left;border-bottom:1px solid #ddd}}.missing{{color:#8b3320}}@media(max-width:850px){{.pair{{grid-template-columns:1fr}}main{{padding:24px 16px}}h1{{font-size:34px}}}}</style>
<main><p>FRONTENDSLM / ORIGINAL RESEARCH PILOT</p><h1>Two small models.<br>One measured baseline.</h1><p class="intro">{len(run['case_ids'])} briefs · {len(rows)} candidate interfaces · Qwen3-4B Architect + Qwen3-VL-4B Critic · NVIDIA L40S on Modal. No training or automatic revisions.</p><p class="intro">These are engineering measurements, not human ratings. Critic claims may be wrong even when their JSON is valid. The comparison includes every requested attempt.</p>{table}<p><a href="report.md">Written report</a> · <a href="summary.json">Measured data</a> · <a href="diagnostics.json">Timing and failure detail</a> · <a href="human-review.jsonl">Unlabeled review queue</a></p>{''.join(sections)}</main></html>"""
    (run_dir / "review.html").write_text(document)
    (run_dir / "human-review.jsonl").write_text("".join(json.dumps(r) + "\n" for r in review_queue))
    write_json(run_dir / "diagnostics.json", diagnostics)
    write_json(run_dir / "artifact-manifest.json", {"run_id": args.run_id, "files": {
        str(p.relative_to(run_dir)): {"sha256": sha256(p.read_bytes()), "bytes": p.stat().st_size}
        for p in sorted(run_dir.rglob("*")) if p.is_file() and p.name != "artifact-manifest.json"
    }})
    print(f"Review report: {run_dir / 'review.html'}")
    print(json.dumps(diagnostics, indent=2))


if __name__ == "__main__":
    main()
